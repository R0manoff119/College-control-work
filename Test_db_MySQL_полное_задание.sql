-- 11. Выбрать id сотрудника, его зарплату и тип выплаты:
-- "Расчет", если день месяца меньше 10; "Аванс", если день месяца 10 или больше.
SELECT
    worker_id,
    amount,
    CASE
        WHEN DAY(paid_at) < 10 THEN 'Расчет'
        ELSE 'Аванс'
    END AS payment_type
FROM salaries;


-- 12. Выбрать короткое имя сотрудника: например, "Збруев Р.".
