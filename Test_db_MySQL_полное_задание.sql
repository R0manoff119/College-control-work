USE Test_db;

-- 1. Выбрать максимальную зарплату за всё время.
SELECT MAX(amount) AS max_salary
FROM salaries;


-- 2. Выбрать описания всех задач, заменив "Починить" на "Исправить".
SELECT REPLACE(description, 'Починить', 'Исправить') AS description
FROM tasks;


-- 3. Выбрать среднюю зарплату за март 2026 года.
SELECT AVG(amount) AS average_salary_march
FROM salaries
WHERE paid_at >= '2026-03-01'
  AND paid_at <  '2026-04-01';


-- 4. Выбрать время, когда была выплачена максимальная зарплата за февраль.
-- Если максимальную сумму выплатили несколько раз, запрос покажет все такие выплаты.
SELECT paid_at
FROM salaries
WHERE paid_at >= '2026-02-01'
  AND paid_at <  '2026-03-01'
  AND amount = (
      SELECT MAX(amount)
      FROM salaries
      WHERE paid_at >= '2026-02-01'
        AND paid_at <  '2026-03-01'
  );


-- 5. Найти количество всех выплат с начала января по конец февраля 2026 года.
SELECT COUNT(*) AS payments_count
FROM salaries
WHERE paid_at >= '2026-01-01'
  AND paid_at <  '2026-03-01';


-- 6. Выбрать сумму всех зарплат, выплаченных 10 числа любого месяца.
SELECT SUM(amount) AS total_salary_paid_on_day_10
FROM salaries
WHERE DAY(paid_at) = 10;


-- 7. Подсчитать количество тегов, которые относятся к задачам с id = 10, 13, 22.
-- Считаем уникальные теги, даже если один тег связан с несколькими указанными задачами.
SELECT COUNT(DISTINCT tag_id) AS tags_count
FROM tags_tasks
WHERE task_id IN (10, 13, 22);


-- 8. Подсчитать процент выполненных задач, поставленных в январе 2026 года.
SELECT
    ROUND(
        SUM(CASE WHEN is_completed = TRUE THEN 1 ELSE 0 END) * 100.0
        / COUNT(*),
        2
    ) AS completed_tasks_percent
FROM tasks
WHERE created_at >= '2026-01-01'
  AND created_at <  '2026-02-01';


-- 9. Выбрать 5 зарплат максимально близких к 330.
SELECT amount
FROM salaries
ORDER BY ABS(amount - 330), amount
LIMIT 5;


-- 10. Выбрать среднее время исполнения задачи за всё время (в минутах).
-- Учитываются задачи, у которых заполнены время начала и время завершения.
SELECT ROUND(AVG(TIMESTAMPDIFF(MINUTE, started_at, completed_at)), 2)
       AS average_execution_time_minutes
FROM tasks
WHERE started_at IS NOT NULL
  AND completed_at IS NOT NULL;


